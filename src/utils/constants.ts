const BENGALI_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toBengaliNumber(num: number | string): string {
  const str = typeof num === 'number' ? Math.round(num).toLocaleString('en-US') : num.toString();
  return str.replace(/\d/g, (digit) => BENGALI_DIGITS[parseInt(digit, 10)]);
}

export function formatBdt(amount: number, language: 'BN' | 'EN' = 'BN'): string {
  const rounded = Math.round(amount);
  if (language === 'BN') {
    return toBengaliNumber(rounded);
  }
  return rounded.toLocaleString('en-US');
}
